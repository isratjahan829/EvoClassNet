"""Collect the deliverables into one folder: manuscript, notebook, result tables and figures.

Everything here is a copy of something generated by the pipeline; nothing is authored in this
script. A manifest records what each file is and which script produced it, so the bundle can be
audited against the repository.
"""
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "results"
FIG = R / "figures"
OUT = ROOT / "deliverables"

PRODUCED_BY = {
    "table_panel.csv": "scripts/analyze2.py — full metric panel, RBD, both splits",
    "table_comparisons.csv": "scripts/analyze2.py — paired tests, equivalence, FDR",
    "table_ablation_v2.csv": "scripts/analyze2.py — amino-acid permutation ablation",
    "table_proteingym.csv": "scripts/analyze_proteingym.py — 217-assay distribution",
    "table_proteingym_comparisons.csv": "scripts/analyze_proteingym.py — per-assay paired tests",
    "proteingym_per_assay.csv": "scripts/analyze_proteingym.py — one row per assay and split",
    "table_genomes.csv": "scripts/analyze_genomes.py — coronavirus genus classification",
    "table_genome_comparisons.csv": "scripts/analyze_genomes.py — against the trivial control",
    "transfer_per_site.csv": "scripts/transfer_by_position.py — per-position transfer",
    "transfer_predictions.csv": "scripts/transfer_by_position.py — scored single substitutions",
    "holdout_predictions.csv": "scripts/holdout_analysis.py — leakage-free predictions",
    "per_site_transfer.csv": "scripts/holdout_analysis.py — per-position, sequence network",
    "feature_ablation.json": "scripts/feature_ablation.py — which feature block transfers",
    "transfer_by_position.json": "scripts/transfer_by_position.py — summary and mixed effects",
    "holdout_analysis.json": "scripts/holdout_analysis.py — VOC ranking, BLOSUM control",
    "esm_control.json": "scripts/esm_control.py — language model sanity controls",
    "stability_check.json": "scripts/stability_check.py — initialisation variance",
    "variant_analysis.json": "scripts/variant_analysis.py — genetic algorithm control",
    "genome_study.json": "scripts/run_genome_study.py — per-run genome results",
    "proteingym_study.json": "scripts/run_proteingym.py — per-assay results",
    "proteingym_confound.json": "scripts/analyze_proteingym.py — confound inventory",
    "run_summary_v2.json": "scripts/analyze2.py — run inventory",
}


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "tables").mkdir(parents=True)
    (OUT / "figures").mkdir(parents=True)
    manifest = {"documents": [], "tables": [], "figures": [], "missing": []}

    for name in ("EvoClassNet_manuscript.docx", "EvoClassNet_report.ipynb", "README.md"):
        src = ROOT / name
        if src.exists():
            shutil.copy2(src, OUT / name)
            manifest["documents"].append({"file": name, "bytes": src.stat().st_size})
        else:
            manifest["missing"].append(name)

    for name, what in PRODUCED_BY.items():
        src = R / name
        if src.exists():
            shutil.copy2(src, OUT / "tables" / name)
            manifest["tables"].append({"file": f"tables/{name}", "produced_by": what,
                                       "bytes": src.stat().st_size})
        else:
            manifest["missing"].append(name)

    # Publication figures first, in their own folder, with the vector versions alongside.
    final = FIG / "final"
    if final.exists():
        (OUT / "figures" / "publication").mkdir(parents=True, exist_ok=True)
        for src in sorted(final.iterdir()):
            if src.suffix.lower() not in (".png", ".pdf"):
                continue
            shutil.copy2(src, OUT / "figures" / "publication" / src.name)
            manifest["figures"].append({"file": f"figures/publication/{src.name}",
                                        "bytes": src.stat().st_size,
                                        "note": "main manuscript figure, 600 dpi PNG and vector PDF"})
    for src in sorted(FIG.glob("*.png")):
        shutil.copy2(src, OUT / "figures" / src.name)
        manifest["figures"].append({"file": f"figures/{src.name}",
                                    "bytes": src.stat().st_size})

    (OUT / "MANIFEST.json").write_text(json.dumps(manifest, indent=1))
    lines = ["# Deliverables", "",
             "Every file here is a copy of pipeline output. `MANIFEST.json` records which script "
             "produced each one.", "",
             "## Documents"]
    for d in manifest["documents"]:
        lines.append(f"* `{d['file']}` ({d['bytes']/1000:.0f} kB)")
    lines += ["", "## Result tables", "", "| File | Produced by |", "|---|---|"]
    for t in manifest["tables"]:
        lines.append(f"| `{t['file']}` | {t['produced_by']} |")
    lines += ["", f"## Figures ({len(manifest['figures'])})", ""]
    for f in manifest["figures"]:
        lines.append(f"* `{f['file']}`")
    if manifest["missing"]:
        lines += ["", "## Not yet generated", ""]
        for m in manifest["missing"]:
            lines.append(f"* {m}")
    (OUT / "README.md").write_text("\n".join(lines) + "\n")

    print(f"deliverables/: {len(manifest['documents'])} documents, "
          f"{len(manifest['tables'])} tables, {len(manifest['figures'])} figures, "
          f"{len(manifest['missing'])} missing")
    for m in manifest["missing"]:
        print("  missing:", m)


if __name__ == "__main__":
    main()
